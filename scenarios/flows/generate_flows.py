#!/usr/bin/env python3
"""Generate the 15 traffic-flow files (5 density levels x 3 lane counts).

Single source of truth: ``scenarios/original/routes.txt``.
Structure and every non-demand attribute are copied from
``scenarios/original/routes.rou.xml`` so that only the demand changes.

Conversion rule (author-confirmed, see docs/HANDOFF.md 10.6)
------------------------------------------------------------
* the numbers in ``routes.txt`` are per-approach, per-direction vehicle counts
  for 100 s (equivalently 1000 SUMO steps of 0.1 s);
* a 1000 s run therefore needs ``number = cell x 10`` vehicles;
* the mean departure headway is ``100 / cell`` seconds, i.e. the bracketed
  value in ``routes.txt`` divided by 10;
* straight : each turning direction = 2 : 1, i.e. L : S : R = 1 : 2 : 1;
* the spread of the Gaussian headway keeps the value used by the original file
  (``normal(mu, 1.0)``); the advisory at the end lists the files where this
  produces negative draws.

Output: ``scenarios/flows/lanes{L}_density{D}.rou.xml`` (15 files).

Usage (from anywhere):
    python3 scenarios/flows/generate_flows.py
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ROUTES_TXT = ROOT / "scenarios" / "original" / "routes.txt"
BASE_ROU = ROOT / "scenarios" / "original" / "routes.rou.xml"
OUT_DIR = ROOT / "scenarios" / "flows"

SCALE = 10          # routes.txt counts are per 100 s -> x10 for a 1000 s run
SIGMA = 1.0         # fixed headway spread, same as scenarios/original/routes.rou.xml
OPPOSITE = {("north", "south"), ("south", "north"),
            ("east", "west"), ("west", "east")}


def parse_counts():
    """(level, lanes) -> {'straight': int, 'turn': int, 'bracket': float|None}."""
    cells = {}
    for line in ROUTES_TXT.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        level_text, rest = line.split(":", 1)
        pairs = re.findall(r"(\d+)/(\d+)\s*(?:\(([\d.]+)\))?", rest)
        if len(pairs) != 3:
            raise SystemExit("unexpected routes.txt line: %r" % line)
        for column, (straight, turn, bracket) in enumerate(pairs):
            lanes = column + 2           # column 1 -> 2 lanes, 2 -> 3, 3 -> 4
            cells[(int(level_text), lanes)] = {
                "straight": int(straight),
                "turn": int(turn),
                "bracket": float(bracket) if bracket else None,
            }
    return cells


def parse_base():
    root = ET.parse(BASE_ROU).getroot()
    routes = [(r.get("id"), r.get("edges")) for r in root.findall("route")]
    flows = [dict(f.attrib) for f in root.findall("flow")]
    return routes, flows


def is_straight(route_id):
    origin, _, destination = route_id.partition("2")
    return (origin, destination) in OPPOSITE


def build_file(lanes, level, cell, routes, flows):
    straight_c = cell["straight"]
    turn_c = cell["turn"]
    lines = [
        "<?xml version='1.0' encoding='UTF-8'?>",
        "",
        "<!--",
        "  DSIP-RR demand file generated by scenarios/flows/generate_flows.py",
        "  DO NOT EDIT BY HAND - edit scenarios/original/routes.txt and regenerate.",
        "",
        "  source      : scenarios/original/routes.txt  (level %d)" % level,
        "  lanes       : %d per approach (two-way %d-lane)" % (lanes, lanes * 2),
        "  horizon     : 0-1000 s",
        "  counts      : straight %d, each turning direction %d  (per approach)"
        % (straight_c * SCALE, turn_c * SCALE),
        "  headway     : straight %.4f s, each turning direction %.4f s"
        % (100.0 / straight_c, 100.0 / turn_c),
        "  conversion  : routes.txt count x %d ; headway = 100 / count seconds"
        % SCALE,
        "  ratio       : straight : each turning direction = 2 : 1  (L:S:R = 1:2:1)",
        "  spread      : normal(mu, %.1f), the same convention as the original" % SIGMA,
        "                scenarios/original/routes.rou.xml",
        "",
        "  NOT a reproduction of a manuscript experiment on its own: the step",
        "  length (1 s vs 0.1 s) and the lane-count <-> net mapping are still open",
        "  decisions; see scenarios/flows/README.md.",
        "-->",
        "",
        "<routes>",
    ]
    for rid, edges in routes:
        lines.append('    <route edges="%s" id="%s" />' % (edges, rid))
    lines.append("")
    for flow in flows:
        rid = flow["route"]
        cell_value = straight_c if is_straight(rid) else turn_c
        lines.append(
            '    <flow begin="%s" departInterval="normal(%.10g, %.1f)" '
            'departPos="%s" departSpeed="%s" end="%s" id="%s" number="%d" '
            'route="%s" seed="%s" type="%s" />'
            % (flow["begin"], 100.0 / cell_value, SIGMA, flow["departPos"],
               flow["departSpeed"], flow["end"], flow["id"],
               cell_value * SCALE, rid, flow["seed"], flow["type"]))
    lines += ["</routes>", ""]
    return "\n".join(lines)


def main():
    cells = parse_counts()
    routes, flows = parse_base()
    if len(routes) != 12 or len(flows) != 12:
        raise SystemExit("expected 12 routes and 12 flows in the base file")
    if sum(1 for rid, _ in routes if is_straight(rid)) != 4:
        raise SystemExit("expected 4 straight routes in the base file")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print("%-24s %-5s %-2s %10s %9s %10s %9s %9s"
          % ("file", "lanes", "lv", "N_straight", "N_turn", "h_straight",
             "h_turn", "veh/run"))
    written = []
    for level in sorted({lvl for lvl, _ in cells}):
        for lanes in (2, 3, 4):
            cell = cells[(level, lanes)]
            path = OUT_DIR / ("lanes%d_density%d.rou.xml" % (lanes, level))
            path.write_text(build_file(lanes, level, cell, routes, flows),
                            encoding="utf-8")
            written.append(path)
            total = 4 * (cell["straight"] + 2 * cell["turn"]) * SCALE
            print("%-24s %-5d %-2d %10d %9d %10.4f %9.4f %9d"
                  % (path.name, lanes, level, cell["straight"] * SCALE,
                     cell["turn"] * SCALE, 100.0 / cell["straight"],
                     100.0 / cell["turn"], total))

    print()
    print("written: %d files in %s" % (len(written), OUT_DIR))
    tight = [(level, lanes, 100.0 / cells[(level, lanes)]["straight"])
             for (level, lanes) in sorted(cells)
             if 100.0 / cells[(level, lanes)]["straight"] < 3 * SIGMA]
    print()
    print("ADVISORY: headway spread is fixed at sigma=%.1f s (original convention)."
          % SIGMA)
    print("  Files whose mean straight headway is below %.1f s will draw negative"
          % (3 * SIGMA))
    print("  intervals; SUMO turns those into immediate departures. Affected:")
    for level, lanes, headway in tight:
        print("    lanes%d_density%d.rou.xml : straight headway %.3f s"
              % (lanes, level, headway))
    return 0


if __name__ == "__main__":
    sys.exit(main())
